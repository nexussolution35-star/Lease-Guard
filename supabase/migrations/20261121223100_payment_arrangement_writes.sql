-- Recording, editing, closing and cancelling payment arrangements (ticket M7-03). An arrangement is a monitoring record
-- of an agreement between the tenant and the owner or manager: LeaseGuard never collects, processes or verifies a
-- payment. An instalment's outcome is recorded by the property manager (or flagged for review from a verified
-- statement by the arrangement-reminders job); nothing here moves money.
--
--   * Signed-in callers never write `payment_arrangements` or `arrangement_installments` directly any more (INSERT,
--     UPDATE and DELETE and the writer policies are withdrawn; members still read). They record, edit, close and
--     cancel through `public.record_payment_arrangement`, `public.update_payment_arrangement`,
--     `public.close_payment_arrangement` and `public.record_arrangement_installment_outcome` (SECURITY DEFINER, company
--     admins and property managers only, 42501 otherwise).
--   * The instalment schedule is generated by the database from the terms (`private.arrangement_schedule`, the same
--     schedule as `generateInstallmentSchedule` in @leaseguard/domain): each instalment is the agreed amount except
--     the last, which is the remainder; weekly and fortnightly add 7 and 14 days, monthly keeps the day of the month
--     (clamped to the month's end). The final instalment date is the schedule's last due date: given, it must agree.
--   * The terms are checked in words (`private.arrangement_terms_problem`, 22023): positive balance and instalment, an
--     instalment no larger than the balance, at most 260 instalments, agreed on or before today (Johannesburg), first
--     instalment on or after the agreement.
--   * Guard (every role, `private.guard_payment_arrangement`): one active arrangement per tenant (in words, and a
--     partial unique index); the tenant, property, unit, lease and who agreed it are fixed; a closed arrangement
--     (completed, defaulted or cancelled) is read-only; status moves proposed -> active | cancelled and active ->
--     completed | defaulted | cancelled only; closing stamps `closed_on` (and, for a signed-in caller,
--     `closed_by_user_id`).
--   * The schedule terms change only while no instalment outcome (paid, missed, waived) is recorded; the schedule is
--     then generated again.
--   * Every change is audited on the arrangement: created, updated (the changed fields), closed or cancelled (with the
--     reason), and each instalment outcome recorded or cleared.
--   * While active, an arrangement keeps suppressing normal arrears reminders for its tenant (unchanged: the outbound
--     gate and arrears monitoring read `status` and `suppress_arrears_reminders`). Nothing here creates a tenant
--     message or a monitoring event.

