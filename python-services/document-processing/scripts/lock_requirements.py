"""Regenerate requirements.txt, the fully pinned runtime lock installed by the Docker image.

pyproject.toml is the single source of truth for dependencies. This resolves its runtime
dependencies (no extras, not the service itself) with pip and writes every resolved package as a
canonical `name==version` pin, sorted by name.

Resolve inside the image's base so platform-specific dependencies match the runtime (Linux,
the Python version in the Dockerfile). From python-services/document-processing:

    docker run --rm -v "$PWD":/src -w /src -u "$(id -u):$(id -g)" -e HOME=/tmp \\
        python:3.14.10-slim-trixie python scripts/lock_requirements.py

Use the same image tag as the Dockerfile's FROM line; the script refuses to run elsewhere unless
`--any-platform` is passed.
"""

import argparse
import json
import platform
import re
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = "# Generated by scripts/lock_requirements.py from pyproject.toml. Do not edit by hand."


def canonical_name(name: str) -> str:
    """PEP 503 normalised project name: lowercase, runs of `-`, `_` and `.` become `-`."""
    return re.sub(r"[-_.]+", "-", name).lower()


def dockerfile_python() -> str | None:
    """The Python version pinned by the Dockerfile's base image (`python:3.14.10-slim-...`)."""
    match = re.search(r"^FROM\s+python:(\d+\.\d+\.\d+)-", (ROOT / "Dockerfile").read_text(), re.M)
    return match.group(1) if match else None


def check_platform() -> None:
    expected = dockerfile_python()
    problems: list[str] = []
    if sys.platform != "linux":
        problems.append(f"this is {sys.platform}, the image is Linux")
    if expected is None:
        problems.append("the Dockerfile does not pin a python:X.Y.Z-* base image")
    elif platform.python_version() != expected:
        problems.append(f"this is Python {platform.python_version()}, the image has {expected}")
    if problems:
        sys.exit(
            "Refusing to lock: "
            + "; ".join(problems)
            + ".\nRun it in the base image (see this script's docstring) or pass --any-platform."
        )


def resolve(requirements: list[str]) -> list[tuple[str, str]]:
    report = subprocess.run(  # noqa: S603 - fixed arguments; requirements come from pyproject.toml
        [
            sys.executable,
            "-m",
            "pip",
            "install",
            "--dry-run",
            "--ignore-installed",
            "--quiet",
            "--disable-pip-version-check",
            "--report",
            "-",
            *requirements,
        ],
        check=True,
        capture_output=True,
        text=True,
    )
    resolved = {
        canonical_name(item["metadata"]["name"]): item["metadata"]["version"]
        for item in json.loads(report.stdout)["install"]
    }
    return sorted(resolved.items())


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--any-platform",
        action="store_true",
        help="lock with this interpreter even if it is not the Docker image's Linux and Python",
    )
    if not parser.parse_args().any_platform:
        check_platform()

    project = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]
    resolved = resolve(project["dependencies"])
    if canonical_name(project["name"]) in dict(resolved):
        sys.exit("the service itself was resolved; check pyproject.toml dependencies")
    lines = [
        HEADER,
        f"# Resolved for CPython {platform.python_version()} on {sys.platform}/"
        f"{platform.machine()}; regenerate with the command in that script's docstring.",
        *(f"{name}=={version}" for name, version in resolved),
    ]
    (ROOT / "requirements.txt").write_text("\n".join(lines) + "\n")
    print(f"wrote {len(resolved)} pinned packages to requirements.txt")


if __name__ == "__main__":
    main()
