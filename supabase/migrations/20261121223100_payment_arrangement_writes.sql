create function public.record_payment_arrangement(
  p_company_id uuid,
  p_tenant_id uuid,
  p_property_id uuid,
  p_outstanding_balance numeric,
  p_installment_amount numeric,
  p_frequency public.installment_frequency,
  p_first_installment_date date,
  p_final_installment_date date default null,
  p_unit_id uuid default null,
  p_lease_id uuid default null,
  p_status public.arrangement_status default 'active',
  p_agreed_on date default null,
  p_notes text default ''
)
returns uuid
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_tenant public.tenants;
  v_property public.properties;
  v_lease public.leases;
  v_count integer;
  v_agreed_on constant date := coalesce(p_agreed_on, private.sa_today());
  v_problem text;
  v_final date;
  v_id uuid;
begin
  if (select auth.uid()) is null or not private.can_write(p_company_id) then
    raise exception 'Only company admins and property managers can record payment arrangements' using errcode = '42501';
  end if;

  select * into v_tenant from public.tenants t where t.company_id = p_company_id and t.id = p_tenant_id;
  if not found then
    raise exception 'The tenant is not in this workspace' using errcode = 'P0002';
  end if;
  select * into v_property from public.properties p where p.company_id = p_company_id and p.id = p_property_id;
  if not found then
    raise exception 'The property is not in this workspace' using errcode = 'P0002';
  end if;
  if p_status not in ('proposed', 'active') then
    raise exception 'A new arrangement is proposed or active.' using errcode = '22023';
  end if;

  -- The lease the arrears are under: the one given, else the tenant's single lease in force at the property (and unit).
  if p_lease_id is not null then
    select * into v_lease from public.leases l where l.company_id = p_company_id and l.id = p_lease_id;
    if not found then
      raise exception 'The lease is not in this workspace' using errcode = 'P0002';
    end if;
    if v_lease.tenant_id <> p_tenant_id or v_lease.property_id <> p_property_id
       or (p_unit_id is not null and v_lease.unit_id <> p_unit_id) then
      raise exception 'Lease % is not a lease of % at %.', v_lease.reference, v_tenant.trading_name,
        v_property.name || case when p_unit_id is not null then ' for that unit' else '' end
        using errcode = '22023';
    end if;
  else
    select count(*) into v_count from public.leases l
    where l.company_id = p_company_id and l.tenant_id = p_tenant_id and l.property_id = p_property_id
      and (p_unit_id is null or l.unit_id = p_unit_id) and l.status in ('active', 'expiring');
    if v_count = 0 then
      raise exception '% has no lease in force at %. Choose the lease the arrears are under.', v_tenant.trading_name, v_property.name
        using errcode = '22023';
    elsif v_count > 1 then
      raise exception '% has % leases in force at %. Choose the unit or the lease.', v_tenant.trading_name, v_count, v_property.name
        using errcode = '22023';
    end if;
    select * into v_lease from public.leases l
    where l.company_id = p_company_id and l.tenant_id = p_tenant_id and l.property_id = p_property_id
      and (p_unit_id is null or l.unit_id = p_unit_id) and l.status in ('active', 'expiring');
  end if;

  v_problem := private.arrangement_terms_problem(
    p_outstanding_balance, p_installment_amount, p_frequency, p_first_installment_date, p_final_installment_date, v_agreed_on
  );
  if v_problem is not null then
    raise exception '%', v_problem using errcode = '22023';
  end if;
  select max(s.due_date) into v_final
  from private.arrangement_schedule(p_outstanding_balance, p_installment_amount, p_frequency, p_first_installment_date) s;

  insert into public.payment_arrangements (
    company_id, tenant_id, property_id, unit_id, lease_id, outstanding_balance, installment_amount, frequency,
    first_installment_date, final_installment_date, status, agreed_by_user_id, agreed_on, notes
  )
  values (
    p_company_id, p_tenant_id, p_property_id, v_lease.unit_id, v_lease.id, p_outstanding_balance, p_installment_amount,
    p_frequency, p_first_installment_date, v_final, p_status, (select auth.uid()), v_agreed_on, coalesce(btrim(p_notes), '')
  )
  returning id into v_id;

  perform private.write_arrangement_schedule(p_company_id, v_id);
  return v_id;
end;
$$;
revoke all on function public.record_payment_arrangement(
