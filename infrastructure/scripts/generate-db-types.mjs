#!/usr/bin/env node
/**
 * Regenerates backend/src/infrastructure/database/database.types.ts from the local Supabase database
 * (`pnpm db:types`). Start the stack and apply migrations first (`pnpm db:start`, `pnpm db:reset`).
 *
 *   node infrastructure/scripts/generate-db-types.mjs                  write the types file
 *   node infrastructure/scripts/generate-db-types.mjs --check          exit 1 if the file is out of date
 *   node infrastructure/scripts/generate-db-types.mjs --output <file>  write somewhere else
 *
 * Runs the repository's own Supabase CLI (root devDependency): `supabase gen types typescript
 * --schema public`. With CLI 3.x the local stack is the default target (`--local` is deprecated and
 * only prints a warning). The file is replaced only when the CLI succeeds and its output looks like a
 * complete types module; it is written to a temporary file and renamed, so a failed or interrupted
 * run never leaves an empty or partial file.
 */
import { spawn } from 'node:child_process'
import { existsSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { parseArgs } from 'node:util'

const REPO_ROOT = path.resolve(import.meta.dirname, '../..')
const DEFAULT_OUTPUT = path.join(REPO_ROOT, 'backend/src/infrastructure/database/database.types.ts')
const SUPABASE_BIN = path.join(REPO_ROOT, 'node_modules/.bin', process.platform === 'win32' ? 'supabase.cmd' : 'supabase')
const GEN_ARGS = ['gen', 'types', 'typescript', '--schema', 'public']

const HEADER = `// Generated by \`pnpm db:types\` (infrastructure/scripts/generate-db-types.mjs) from the local
// Supabase database schema (supabase/migrations). Do not edit: change a migration and regenerate.
`

/** Markers every complete output of the generator contains. */
const REQUIRED_MARKERS = ['export type Database', 'export type Tables<', 'export const Constants']

function fail(message) {
  console.error(`generate-db-types: ${message}`)
  process.exit(1)
}

function generate() {
  return new Promise((resolve, reject) => {
    const child = spawn(SUPABASE_BIN, GEN_ARGS, { cwd: REPO_ROOT, stdio: ['ignore', 'pipe', 'inherit'] })
    const chunks = []
    child.stdout.on('data', (chunk) => chunks.push(chunk))
    child.on('error', reject)
    child.on('close', (code, signal) => {
      if (code === 0) resolve(Buffer.concat(chunks).toString('utf8'))
      else reject(new Error(`supabase ${GEN_ARGS.join(' ')} failed (${signal ?? `exit code ${code}`}); is the local stack running (pnpm db:start)?`))
    })
  })
}

const { values } = parseArgs({
  options: { check: { type: 'boolean', default: false }, output: { type: 'string' } },
})
const output = path.resolve(values.output ?? DEFAULT_OUTPUT)

if (!existsSync(SUPABASE_BIN)) fail(`Supabase CLI not found at ${path.relative(REPO_ROOT, SUPABASE_BIN)}; run pnpm install`)

let generated
try {
  generated = await generate()
} catch (error) {
  fail(error instanceof Error ? error.message : String(error))
}

const missing = REQUIRED_MARKERS.filter((marker) => !generated.includes(marker))
if (missing.length > 0) {
  fail(`unexpected generator output (missing ${missing.join(', ')}); ${path.relative(REPO_ROOT, output)} was left unchanged`)
}

const content = `${HEADER}\n${generated.endsWith('\n') ? generated : `${generated}\n`}`
const relativeOutput = path.relative(REPO_ROOT, output)

if (values.check) {
  const current = existsSync(output) ? readFileSync(output, 'utf8') : ''
  if (current !== content) fail(`${relativeOutput} is out of date; run pnpm db:types`)
  console.log(`generate-db-types: ${relativeOutput} is up to date`)
} else {
  const temporary = `${output}.${process.pid}.tmp`
  try {
    writeFileSync(temporary, content)
    renameSync(temporary, output)
  } catch (error) {
    rmSync(temporary, { force: true })
    fail(error instanceof Error ? error.message : String(error))
  }
  console.log(`generate-db-types: wrote ${relativeOutput}`)
}
