-- --------------------------------------------------------------------------- close and cancel

create function public.close_payment_arrangement(
  p_company_id uuid,
  p_arrangement_id uuid,
  p_status public.arrangement_status,
  p_reason text default null
)
returns uuid
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_old public.payment_arrangements;
  v_reason constant text := nullif(btrim(coalesce(p_reason, '')), '');
begin
  if (select auth.uid()) is null or not private.can_write(p_company_id) then
    raise exception 'Only company admins and property managers can close payment arrangements' using errcode = '42501';
  end if;
  if p_status is null or p_status not in ('completed', 'defaulted', 'cancelled') then
    raise exception 'An arrangement closes as completed or defaulted, or is cancelled.' using errcode = '22023';
  end if;
  if p_status = 'cancelled' and v_reason is null then
    raise exception 'Give the reason for cancelling the arrangement.' using errcode = '22023';
  end if;
  if v_reason is not null and length(v_reason) > 1000 then
    raise exception 'The reason can be at most 1000 characters.' using errcode = '22023';
  end if;

  select * into v_old from public.payment_arrangements a where a.company_id = p_company_id and a.id = p_arrangement_id for update;
  if not found then
    raise exception 'The arrangement is not in this workspace' using errcode = 'P0002';
  end if;
  if v_old.status = 'proposed' and p_status <> 'cancelled' then
    raise exception 'A proposed arrangement was never active, so it can only be cancelled.' using errcode = 'P0001';
  end if;

  -- The guard refuses a closed arrangement and stamps who closed it and when.
  update public.payment_arrangements a set status = p_status, close_reason = v_reason
  where a.company_id = p_company_id and a.id = p_arrangement_id;
  return p_arrangement_id;
end;
$$;
revoke all on function public.close_payment_arrangement(uuid, uuid, public.arrangement_status, text) from public, anon;
grant execute on function public.close_payment_arrangement(uuid, uuid, public.arrangement_status, text) to authenticated;
comment on function public.close_payment_arrangement(uuid, uuid, public.arrangement_status, text) is
  'A company writer closes an active arrangement as completed or defaulted, or cancels a proposed or active one (a '
  'reason is required to cancel). Normal arrears reminders resume for the tenant from then on. Stamps closed_on and '
  'closed_by_user_id; audited. P0001 when it is already closed or a proposed one is closed rather than cancelled.';

-- --------------------------------------------------------------------------- instalment outcomes

-- A property manager's confirmation of what happened to an instalment: paid, missed or waived; 'scheduled' clears a
-- recorded outcome (back to 'reminder_sent' when a reminder went out). LeaseGuard never verifies a payment.
create function public.record_arrangement_installment_outcome(
  p_company_id uuid,
  p_arrangement_id uuid,
  p_installment_id uuid,
  p_status public.installment_status,
  p_note text default null
)
returns uuid
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_arrangement public.payment_arrangements;
  v_installment public.arrangement_installments;
  v_note constant text := nullif(btrim(coalesce(p_note, '')), '');
  v_status public.installment_status := p_status;
begin
  if (select auth.uid()) is null or not private.can_write(p_company_id) then
    raise exception 'Only company admins and property managers can record instalment outcomes' using errcode = '42501';
  end if;
  if p_status is null or p_status = 'reminder_sent' then
    raise exception 'An instalment is recorded as paid, missed or waived, or cleared.' using errcode = '22023';
  end if;
  if v_note is not null and length(v_note) > 1000 then
    raise exception 'The note can be at most 1000 characters.' using errcode = '22023';
  end if;

  select * into v_arrangement from public.payment_arrangements a
  where a.company_id = p_company_id and a.id = p_arrangement_id for update;
  if not found then
    raise exception 'The arrangement is not in this workspace' using errcode = 'P0002';
  end if;
  select * into v_installment from public.arrangement_installments i
  where i.company_id = p_company_id and i.arrangement_id = p_arrangement_id and i.id = p_installment_id for update;
  if not found then
    raise exception 'The instalment is not in this arrangement' using errcode = 'P0002';
  end if;
  if v_arrangement.status <> 'active' then
    raise exception 'Instalment outcomes are recorded while the arrangement is active; this one is %.',
      private.arrangement_status_label(v_arrangement.status)
      using errcode = 'P0001';
  end if;
  if p_status = 'missed' and v_installment.due_date > private.sa_today() then
    raise exception 'Instalment % is due on %, so it cannot be missed yet.', v_installment.sequence, to_char(v_installment.due_date, 'DD Mon YYYY')
      using errcode = 'P0001';
  end if;
  if p_status = 'scheduled' and v_installment.reminder_sent_at is not null then
    v_status := 'reminder_sent';
  end if;

  update public.arrangement_installments i set
    status = v_status,
    confirmed_by_user_id = case when v_status = 'confirmed_paid' then (select auth.uid()) end,
    confirmed_on = case when v_status = 'confirmed_paid' then private.sa_today() end,
    outcome_recorded_by_user_id = case when v_status in ('confirmed_paid', 'missed', 'waived') then (select auth.uid()) end,
    outcome_recorded_at = case when v_status in ('confirmed_paid', 'missed', 'waived') then now() end,
    notes = case when v_status in ('confirmed_paid', 'missed', 'waived') then v_note end
  where i.company_id = p_company_id and i.id = p_installment_id;
  return p_installment_id;
end;
$$;
revoke all on function public.record_arrangement_installment_outcome(uuid, uuid, uuid, public.installment_status, text) from public, anon;
grant execute on function public.record_arrangement_installment_outcome(uuid, uuid, uuid, public.installment_status, text) to authenticated;
comment on function public.record_arrangement_installment_outcome(uuid, uuid, uuid, public.installment_status, text) is
  'A company writer records an instalment of an active arrangement as paid, missed or waived (a manager confirmation; '
  'LeaseGuard never verifies payments), or clears it (scheduled). A future instalment cannot be missed. Stamps who and '
  'when; audited on the arrangement. P0001 when the arrangement is not active; P0002 for another company''s.';
