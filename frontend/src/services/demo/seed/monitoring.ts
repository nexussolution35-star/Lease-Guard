interface CompanyRuleSettings {
  companyId: EntityId
  ids: Record<MonitoringEventType, EntityId>
  createdAt: string
  assignee: EntityId
  config: Record<MonitoringEventType, MonitoringRuleConfig>
}

function rulesFor(settings: CompanyRuleSettings): readonly MonitoringRule[] {
  return RULE_TEMPLATES.map((template) => ({
    id: settings.ids[template.eventType],
    companyId: settings.companyId,
    createdAt: settings.createdAt,
    updatedAt: settings.createdAt,
    eventType: template.eventType,
    name: template.name,
    description: template.description,
    enabled: true,
    defaultPriority: template.defaultPriority,
    config: settings.config[template.eventType],
    defaultAssigneeUserId: settings.assignee,
  }))
}

