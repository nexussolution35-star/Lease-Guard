create function private.audit_payment_arrangement()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_fields constant text[] := array[
    'status', 'outstanding_balance', 'installment_amount', 'frequency', 'first_installment_date',
    'final_installment_date', 'agreed_on', 'suppress_arrears_reminders', 'notes', 'closed_on', 'close_reason'
  ];
  v_old jsonb;
  v_new constant jsonb := to_jsonb(new);
  v_changes jsonb;
  v_tenant text;
  v_lease text;
  v_summary text;
begin
  select t.trading_name into v_tenant from public.tenants t where t.company_id = new.company_id and t.id = new.tenant_id;
  select l.reference into v_lease from public.leases l where l.company_id = new.company_id and l.id = new.lease_id;

  if tg_op = 'INSERT' then
    perform private.write_audit(
      new.company_id, 'create', 'payment_arrangement', new.id,
      format('Payment arrangement recorded for %s under lease %s', v_tenant, v_lease),
      jsonb_build_array(
        private.field_change('status', null::text, new.status::text),
        private.field_change('outstanding_balance', null::numeric, new.outstanding_balance),
        private.field_change('installment_amount', null::numeric, new.installment_amount),
        private.field_change('frequency', null::text, new.frequency::text),
        private.field_change('first_installment_date', null::date, new.first_installment_date),
        private.field_change('final_installment_date', null::date, new.final_installment_date),
        private.field_change('agreed_on', null::date, new.agreed_on)
      )
    );
    return null;
  end if;

  v_old := to_jsonb(old);
  select jsonb_agg(
    jsonb_build_object('field', f.field, 'before', v_old -> f.field, 'after', v_new -> f.field)
    order by f.ordinality
  )
  into v_changes
  from unnest(v_fields) with ordinality as f (field, ordinality)
  where (v_old -> f.field) is distinct from (v_new -> f.field);
  if v_changes is null then
    return null;
  end if;

  v_summary := case
    when new.status is distinct from old.status and new.status = 'cancelled' then
      format('Payment arrangement for %s cancelled', v_tenant)
    when new.status is distinct from old.status and new.status in ('completed', 'defaulted') then
      format('Payment arrangement for %s closed as %s', v_tenant, private.arrangement_status_label(new.status))
    when new.status is distinct from old.status and new.status = 'active' then
      format('Payment arrangement for %s made active', v_tenant)
    else format('Payment arrangement for %s updated', v_tenant)
  end;
  perform private.write_audit(new.company_id, 'update', 'payment_arrangement', new.id, v_summary, v_changes);
  return null;
end;
$$;
revoke all on function private.audit_payment_arrangement() from public, anon, authenticated;

create trigger audit_change after insert or update on public.payment_arrangements
  for each row execute function private.audit_payment_arrangement();

-- An instalment outcome recorded or cleared is audited on its arrangement (status changes to and from paid, missed or
-- waived; a reminder being sent is not an outcome).
create function private.audit_arrangement_installment()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_outcomes constant public.installment_status[] := '{confirmed_paid,missed,waived}';
  v_total integer;
  v_label text;
begin
  if new.status is not distinct from old.status
     or not (new.status = any (v_outcomes) or old.status = any (v_outcomes)) then
    return null;
  end if;
  select count(*) into v_total from public.arrangement_installments i
  where i.company_id = new.company_id and i.arrangement_id = new.arrangement_id;
  v_label := case new.status
    when 'confirmed_paid' then 'paid'
    when 'missed' then 'missed'
    when 'waived' then 'waived'
    else 'not yet recorded'
  end;
  perform private.write_audit(
    new.company_id, 'update', 'payment_arrangement', new.arrangement_id,
    format('Instalment %s of %s (due %s) recorded as %s', new.sequence, v_total, to_char(new.due_date, 'DD Mon YYYY'), v_label),
    jsonb_build_array(
      private.field_change('installmentId', new.id, new.id),
      private.field_change('installmentStatus', old.status::text, new.status::text),
      private.field_change('installmentNotes', old.notes, new.notes)
    )
  );
  return null;
end;
$$;
revoke all on function private.audit_arrangement_installment() from public, anon, authenticated;

create trigger audit_outcome after update of status on public.arrangement_installments
  for each row execute function private.audit_arrangement_installment();

