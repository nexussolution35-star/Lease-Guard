interface InstallmentSpec {
  dueDate: ISODate
  amount: ZAR
  status: InstallmentStatus
  reminderSentAt?: string
  confirmedByUserId?: string
  confirmedOn?: ISODate
  notes?: string
}

function schedule(arrangementId: string, specs: readonly InstallmentSpec[]): readonly ArrangementInstallment[] {
  return specs.map((spec, index) => ({
    id: `${arrangementId}_i${index + 1}`,
    arrangementId,
    sequence: index + 1,
    ...spec,
  }))
}

