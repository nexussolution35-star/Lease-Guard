-- Null arguments keep the current value. A new final instalment date is checked against the schedule; left out, it
-- follows the schedule.
create function public.update_payment_arrangement(
  p_company_id uuid,
  p_arrangement_id uuid,
  p_outstanding_balance numeric default null,
  p_installment_amount numeric default null,
  p_frequency public.installment_frequency default null,
  p_first_installment_date date default null,
  p_final_installment_date date default null,
  p_agreed_on date default null,
  p_status public.arrangement_status default null,
  p_notes text default null
)
returns uuid
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_old public.payment_arrangements;
  v_balance numeric;
  v_amount numeric;
  v_frequency public.installment_frequency;
  v_first date;
  v_agreed_on date;
  v_schedule_changed boolean;
  v_problem text;
  v_final date;
begin
  if (select auth.uid()) is null or not private.can_write(p_company_id) then
    raise exception 'Only company admins and property managers can edit payment arrangements' using errcode = '42501';
  end if;

  select * into v_old from public.payment_arrangements a where a.company_id = p_company_id and a.id = p_arrangement_id for update;
  if not found then
    raise exception 'The arrangement is not in this workspace' using errcode = 'P0002';
  end if;
  if v_old.status in ('completed', 'defaulted', 'cancelled') then
    raise exception 'This arrangement is % and can no longer change.', private.arrangement_status_label(v_old.status)
      using errcode = 'P0001';
  end if;
  if p_status is not null and p_status not in ('proposed', 'active') then
    raise exception 'Close or cancel the arrangement to end it.' using errcode = '22023';
  end if;

  v_balance := coalesce(p_outstanding_balance, v_old.outstanding_balance);
  v_amount := coalesce(p_installment_amount, v_old.installment_amount);
  v_frequency := coalesce(p_frequency, v_old.frequency);
  v_first := coalesce(p_first_installment_date, v_old.first_installment_date);
  v_agreed_on := coalesce(p_agreed_on, v_old.agreed_on);
  v_schedule_changed := v_balance <> v_old.outstanding_balance or v_amount <> v_old.installment_amount
    or v_frequency <> v_old.frequency or v_first <> v_old.first_installment_date;

  if v_schedule_changed and exists (
    select 1 from public.arrangement_installments i
    where i.company_id = p_company_id and i.arrangement_id = p_arrangement_id and i.status in ('confirmed_paid', 'missed', 'waived')
  ) then
    raise exception 'Instalment outcomes are already recorded, so the schedule is fixed. Cancel this arrangement and record a new one.'
      using errcode = 'P0001';
  end if;

  v_problem := private.arrangement_terms_problem(
    v_balance, v_amount, v_frequency, v_first,
    coalesce(p_final_installment_date, case when v_schedule_changed then null else v_old.final_installment_date end),
    v_agreed_on
  );
  if v_problem is not null then
    raise exception '%', v_problem using errcode = '22023';
  end if;
  select max(s.due_date) into v_final from private.arrangement_schedule(v_balance, v_amount, v_frequency, v_first) s;

  update public.payment_arrangements a set
    outstanding_balance = v_balance,
    installment_amount = v_amount,
    frequency = v_frequency,
    first_installment_date = v_first,
    final_installment_date = v_final,
    agreed_on = v_agreed_on,
    status = coalesce(p_status, a.status),
    notes = coalesce(btrim(p_notes), a.notes)
  where a.company_id = p_company_id and a.id = p_arrangement_id;

  if v_schedule_changed then
    perform private.write_arrangement_schedule(p_company_id, p_arrangement_id);
  end if;
  return p_arrangement_id;
end;
$$;
