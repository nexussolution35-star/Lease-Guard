import {
  arrangementActions,
  arrangementProgress,
  compareISODate,
  isInstallmentOutcome,
  isoToday,
  nextInstallment,
  overdueInstallments,
  shouldSuppressArrearsReminder,
  type ArrangementInstallment,
  type MonitoringEventListItem,
  type PaymentArrangementListItem,
} from '@leaseguard/domain'
import { Info, Pencil } from 'lucide-react'
import { useState } from 'react'
import { toast } from 'sonner'

import { PageHeader } from '@/components/layout/PageHeader'
import {
  AppLink,
  ConfirmationDialog,
  CurrencyDisplay,
  DataTable,
  DateDisplay,
  EmptyState,
  ErrorState,
  InformationGrid,
  InformationItem,
  LoadingState,
  MetricCard,
  MetricGrid,
  PriorityBadge,
  SectionHeader,
  SignOff,
  StatusBadge,
  StatusDot,
  type DataTableColumn,
} from '@/components/shared'
import { Button } from '@/components/ui/button'
import { useIsCompanyWriter } from '@/features/account/useActiveRole'
import { useMonitoringEventList } from '@/features/monitoring/api/queries'
import { useMemberList } from '@/features/users/api/queries'
import { describeApiError } from '@/lib/data/apiErrors'
import { MAX_LIST_PAGE_SIZE } from '@/lib/data/listParams'
import { labelFor } from '@/lib/labels'
import { cn } from '@/lib/utils'

import { useCancelArrangement, useUpdateArrangement } from '../api/queries'
import { ArrangementFormDialog } from './ArrangementFormDialog'
import { CloseArrangementDialog } from './CloseArrangementDialog'
import { InstallmentOutcomeDialog } from './InstallmentOutcomeDialog'
import { useDateFormatter } from '@/lib/dateFormat'

export interface ArrangementDetailScreenProps {
  arrangement: PaymentArrangementListItem
}

/** In the `lg` rail each detail reads as one row, label left and value right, as in a ledger. */
const RAIL_ITEM = 'lg:grid lg:grid-cols-[7.5rem_minmax(0,1fr)] lg:items-baseline lg:gap-x-3 lg:space-y-0 lg:[&>dt]:font-normal'

const FREQUENCY_TEXT = { weekly: 'Every week', fortnightly: 'Every two weeks', monthly: 'Every month' } as const

/**
 * One payment arrangement: the agreement and who recorded it, its progress, the instalment schedule (generated by the
 * database from the terms, the same rules as `generateInstallmentSchedule` in `@leaseguard/domain`) with each
 * instalment's outcome and who recorded it, what monitoring flagged, and the parties and terms in a side rail. Company
 * admins and property managers edit, activate, close or cancel it and record instalment outcomes, as
 * `arrangementActions` allows. LeaseGuard records the agreement only: there is no payment action anywhere.
 */
export function ArrangementDetailScreen({ arrangement }: ArrangementDetailScreenProps) {
  const { date: formatDate } = useDateFormatter()
  const isWriter = useIsCompanyWriter()
  const [editing, setEditing] = useState(false)
  const [closing, setClosing] = useState(false)
  const [cancelling, setCancelling] = useState(false)
  const [activating, setActivating] = useState(false)
  const [recording, setRecording] = useState<ArrangementInstallment | null>(null)
  const update = useUpdateArrangement()
  const cancel = useCancelArrangement()
  // The date when the screen opened; progress and what is past due are worked out as of this day.
  const [today] = useState(() => isoToday(new Date()))

  const members = useMemberList({ page: 1, pageSize: MAX_LIST_PAGE_SIZE, sort: 'fullName', direction: 'asc' })
  const events = useMonitoringEventList({
    page: 1,
    pageSize: MAX_LIST_PAGE_SIZE,
    type: 'arrangement_attention',
    arrangementId: arrangement.id,
    sort: 'identifiedOn',
    direction: 'desc',
  })

  /** A member's name only when it is loaded: a sign-off never shows a placeholder as if it were a person. */
  const signerOf = (userId: string | undefined) =>
    userId ? members.data?.items.find((member) => member.id.toLowerCase() === userId.toLowerCase())?.fullName : undefined

  /** A signed record whose signer is not (or no longer) a listed member reads as text with its date, never as pending. */
  const signed = (userId: string | undefined, at: string | undefined, text: string) => {
    const by = signerOf(userId)
    if (by) return <SignOff by={by} at={at} />
    return (
      <span className="text-sm">
        {text}
        {at ? (
          <>
            <span className="text-muted-foreground"> · </span>
            <DateDisplay value={at} className="text-muted-foreground tabular-nums" />
          </>
        ) : null}
      </span>
    )
  }

  const actions = arrangementActions(arrangement)
  const canWrite = isWriter && (actions.edit || actions.close || actions.cancel)
  const progress = arrangementProgress(arrangement)
  const next = actions.edit ? nextInstallment(arrangement, today) : undefined
  const pastDue = new Set(arrangement.status === 'active' ? overdueInstallments(arrangement, today).map((i) => i.id) : [])
  const remindersPaused = shouldSuppressArrearsReminder(arrangement.tenantId, [arrangement], today)
  const flagged = events.data?.items ?? []

  async function confirmActivate() {
    try {
      await update.mutateAsync({ id: arrangement.id, changes: { status: 'active' } })
      toast.success(`Arrangement with ${arrangement.tenantName} is active; normal arrears reminders are paused`)
    } catch (error) {
      toast.error('The arrangement was not made active', { description: describeApiError(error, 'Try again in a moment.') })
      throw error
    }
  }

  async function confirmCancel(reason?: string) {
    await cancel.mutateAsync({ id: arrangement.id, cancellation: { reason: reason ?? '' } })
    toast.success(`Arrangement with ${arrangement.tenantName} cancelled`)
  }

  const scheduleColumns: DataTableColumn<ArrangementInstallment>[] = [
    { id: 'sequence', header: '#', cell: (installment) => installment.sequence },
    { id: 'dueDate', header: 'Due', rowHeader: true, cell: (installment) => <DateDisplay value={installment.dueDate} /> },
    { id: 'amount', header: 'Amount', align: 'right', cell: (installment) => <CurrencyDisplay amount={installment.amount} /> },
    {
      id: 'status',
      header: 'Status',
      cell: (installment) =>
        pastDue.has(installment.id) ? (
          <StatusDot tone="warning">Past due, not confirmed</StatusDot>
        ) : (
          <StatusBadge status={installment.status} />
        ),
    },
    {
      id: 'recorded',
      header: 'Recorded',
      hideBelow: 'md',
      cell: (installment) =>
        isInstallmentOutcome(installment.status) ? (
          signed(installment.outcomeRecordedByUserId, installment.outcomeRecordedAt, 'Recorded')
        ) : compareISODate(installment.dueDate, today) <= 0 && arrangement.status === 'active' ? (
          <SignOff pendingLabel="Outcome not recorded" />
        ) : (
          <span className="text-muted-foreground">—</span>
        ),
    },
    {
      id: 'notes',
      header: 'Note',
      hideBelow: 'lg',
      className: 'min-w-40 whitespace-normal',
      cell: (installment) => installment.notes ?? <span className="text-muted-foreground">—</span>,
    },
    ...(isWriter && actions.recordInstallmentOutcomes
      ? [
          {
            id: 'actions',
            header: 'Actions',
            align: 'right' as const,
            cell: (installment: ArrangementInstallment) => (
              <Button
                type="button"
                variant="ghost"
                size="sm"
                onClick={() => setRecording(installment)}
                aria-label={`Record the outcome of instalment ${installment.sequence}`}
              >
                Record outcome
              </Button>
            ),
          },
        ]
      : []),
  ]

  const eventColumns: DataTableColumn<MonitoringEventListItem>[] = [
    {
      id: 'title',
      header: 'Finding',
      className: 'min-w-56 whitespace-normal',
      cell: (event) => (
        <>
          <AppLink to={`/monitoring/${encodeURIComponent(event.id)}`} className="font-medium text-foreground hover:underline">
            {event.title}
          </AppLink>
          <span className="block text-xs text-muted-foreground">{event.recommendedAction}</span>
        </>
      ),
    },
    { id: 'priority', header: 'Priority', hideBelow: 'sm', cell: (event) => <PriorityBadge priority={event.priority} /> },
    { id: 'status', header: 'Status', cell: (event) => <StatusBadge status={event.status} /> },
    { id: 'identifiedOn', header: 'Identified', hideBelow: 'md', cell: (event) => <DateDisplay value={event.identifiedOn} /> },
  ]

  return (
    <section>
      <PageHeader
        title={`Payment arrangement with ${arrangement.tenantName}`}
        status={
          <p className="flex flex-wrap items-center gap-x-2.5 gap-y-1 text-sm text-muted-foreground">
            <span className="font-medium text-foreground">{arrangement.tenantName}</span>
            <span aria-hidden="true">·</span>
            <span className="tabular-nums">{arrangement.leaseReference}</span>
            <span aria-hidden="true">·</span>
            <StatusBadge status={arrangement.status} />
          </p>
        }
        actions={
          canWrite ? (
            <>
              {/* Primary last: making a proposal active, or closing an active arrangement. */}
              {actions.cancel ? (
                <Button type="button" variant="outline" onClick={() => setCancelling(true)}>
                  Cancel arrangement
                </Button>
              ) : null}
              {actions.edit ? (
                <Button type="button" variant="outline" onClick={() => setEditing(true)}>
                  <Pencil aria-hidden="true" />
                  Edit
                </Button>
              ) : null}
              {actions.activate ? (
                <Button type="button" onClick={() => setActivating(true)}>
                  Make active
                </Button>
              ) : null}
              {actions.close ? (
                <Button type="button" onClick={() => setClosing(true)}>
                  Close arrangement
                </Button>
              ) : null}
            </>
          ) : null
        }
      />

      <p role="note" className="mb-6 flex gap-2 rounded-md border border-border bg-muted/40 px-4 py-3 text-sm text-muted-foreground">
        <Info className="mt-0.5 size-4 shrink-0" aria-hidden="true" />
        <span>
          LeaseGuard records this agreement and its schedule; it never takes, processes or verifies a payment. Instalments are
          confirmed by a property manager; a verified statement only flags an instalment for the manager to confirm.{' '}
          {remindersPaused
            ? 'While it is active, normal arrears reminders to the tenant are paused.'
            : arrangement.status === 'proposed'
              ? 'Normal arrears reminders carry on until it is made active.'
              : 'Normal arrears reminders apply again.'}
        </span>
      </p>

      {/* DOM order is the phone order: figures, then the work, then details; from `lg` the details move into a right rail. */}
      <div className="grid gap-8 lg:grid-cols-[minmax(0,1fr)_18rem] lg:gap-x-8 xl:grid-cols-[minmax(0,1fr)_20rem]">
        <MetricGrid className="lg:col-start-1 lg:row-start-1 xl:grid-cols-[1.4fr_1fr_1fr_1fr]">
          <MetricCard lead label="Balance agreed" value={<CurrencyDisplay amount={arrangement.outstandingBalance} />} />
          <MetricCard
            label="Confirmed paid"
            value={<CurrencyDisplay amount={progress.paid} />}
            description={`${progress.paidCount} of ${progress.totalCount} instalments`}
          />
          <MetricCard label="Still to pay" value={<CurrencyDisplay amount={progress.remaining} />} />
          <MetricCard
            label="Next instalment"
            value={next ? <span className="tabular-nums">{formatDate(next.dueDate)}</span> : '—'}
            {...(next ? { description: `Instalment ${next.sequence}` } : {})}
          />
        </MetricGrid>

        <div className="flex min-w-0 flex-col gap-10 lg:col-start-1 lg:row-start-2">
          <section aria-label="Agreement" className="space-y-3">
            <SectionHeader title="Agreement" />
            <div className="divide-y divide-border border-y border-border">
              <div className="flex flex-wrap items-center justify-between gap-2 py-3">
                <span className="text-sm text-muted-foreground">Recorded</span>
                {signed(arrangement.agreedByUserId, arrangement.agreedOn, 'Agreed')}
              </div>
              {arrangement.closedOn ? (
                <div className="flex flex-col gap-1 py-3">
                  <div className="flex flex-wrap items-center justify-between gap-2">
                    <span className="text-sm text-muted-foreground">{labelFor(arrangement.status)}</span>
                    {signed(arrangement.closedByUserId, arrangement.closedOn, labelFor(arrangement.status))}
                  </div>
                  {arrangement.closeReason ? <p className="text-sm">{arrangement.closeReason}</p> : null}
                </div>
              ) : null}
            </div>
          </section>

          <section aria-label="Instalment schedule" className="space-y-3">
            <SectionHeader
              title="Instalment schedule"
              description={`${arrangement.installments.length} ${arrangement.installments.length === 1 ? 'instalment' : 'instalments'} of ${labelFor(arrangement.frequency).toLowerCase()} payments, generated from the agreed terms. The last is the remainder of the balance.`}
            />
            <DataTable
              caption={`Instalment schedule of the arrangement with ${arrangement.tenantName}`}
              columns={scheduleColumns}
              rows={[...arrangement.installments]}
              getRowId={(installment) => installment.id}
            />
          </section>

          <section aria-label="Flagged by monitoring" className="space-y-3">
            <SectionHeader title="Flagged by monitoring" description="Instalments a verified statement shows were not covered, and instalments past due." />
            {events.isPending ? (
              <LoadingState label="Loading what monitoring flagged…" rows={2} />
            ) : events.isError ? (
              <ErrorState title="Could not load the monitoring findings" error={describeApiError(events.error, 'Try again in a moment.')} onRetry={() => void events.refetch()} />
            ) : flagged.length === 0 ? (
              <EmptyState title="Nothing flagged" description="Monitoring has raised nothing for this arrangement." className="py-0" />
            ) : (
              <DataTable caption={`Monitoring findings for the arrangement with ${arrangement.tenantName}`} columns={eventColumns} rows={flagged} getRowId={(event) => event.id} />
            )}
          </section>
        </div>

        <section aria-label="Details" className="space-y-4 lg:col-start-2 lg:row-span-2 lg:row-start-1 lg:border-l lg:border-border lg:pl-8">
          <SectionHeader title="Details" className="[&_h2]:text-sm" />
          <InformationGrid columns={1} className="gap-y-3 sm:grid-cols-2 lg:grid-cols-1">
            <InformationItem
              label="Tenant"
              className={RAIL_ITEM}
              value={
                <AppLink to={`/tenants/${encodeURIComponent(arrangement.tenantId)}`} className="text-foreground hover:underline">
                  {arrangement.tenantName || 'Tenant'}
                </AppLink>
              }
            />
            <InformationItem
              label="Property"
              className={RAIL_ITEM}
              value={
                <AppLink to={`/properties/${encodeURIComponent(arrangement.propertyId)}`} className="text-foreground hover:underline">
                  {arrangement.propertyName || 'Property'}
                </AppLink>
              }
            />
            <InformationItem
              label="Unit"
              className={RAIL_ITEM}
              value={
                <AppLink to={`/units/${encodeURIComponent(arrangement.unitId)}`} className="text-foreground tabular-nums hover:underline">
                  {arrangement.unitNumber || 'Unit'}
                </AppLink>
              }
            />
            <InformationItem
              label="Lease"
              className={RAIL_ITEM}
              value={
                <AppLink to={`/leases/${encodeURIComponent(arrangement.leaseId)}`} className="text-foreground tabular-nums hover:underline">
                  {arrangement.leaseReference || 'Lease'}
                </AppLink>
              }
            />
            <InformationItem label="Instalment" className={RAIL_ITEM} value={<CurrencyDisplay amount={arrangement.installmentAmount} />} />
            <InformationItem label="Frequency" className={RAIL_ITEM} value={FREQUENCY_TEXT[arrangement.frequency]} />
            <InformationItem label="First due" className={RAIL_ITEM} value={<DateDisplay value={arrangement.firstInstallmentDate} className="tabular-nums" />} />
            <InformationItem label="Final due" className={RAIL_ITEM} value={<DateDisplay value={arrangement.finalInstallmentDate} className="tabular-nums" />} />
            <InformationItem label="Agreed on" className={RAIL_ITEM} value={<DateDisplay value={arrangement.agreedOn} className="tabular-nums" />} />
            <InformationItem
              label="Reminders"
              className={RAIL_ITEM}
              value={remindersPaused ? <StatusDot tone="info">Arrears reminders paused</StatusDot> : <StatusDot tone="neutral">Not paused</StatusDot>}
            />
            <InformationItem label="Notes" className={cn(RAIL_ITEM, 'sm:col-span-2 lg:col-span-1')} value={arrangement.notes || undefined} />
          </InformationGrid>
        </section>
      </div>

      {isWriter && actions.edit ? <ArrangementFormDialog open={editing} onOpenChange={setEditing} arrangement={arrangement} /> : null}
      {isWriter && actions.close ? <CloseArrangementDialog open={closing} onOpenChange={setClosing} arrangement={arrangement} /> : null}
      {isWriter && actions.recordInstallmentOutcomes ? (
        <InstallmentOutcomeDialog
          open={recording !== null}
          onOpenChange={(open) => {
            if (!open) setRecording(null)
          }}
          arrangement={arrangement}
          installment={recording}
        />
      ) : null}
      {isWriter && actions.activate ? (
        <ConfirmationDialog
          open={activating}
          onOpenChange={setActivating}
          title={`Make the arrangement with ${arrangement.tenantName} active?`}
          description="Confirm the tenant agreed to these terms. While it is active, the tenant's normal arrears reminders are paused and you are told as each instalment falls due. An instalment reminder reaches the tenant only after a property manager approves it."
          confirmLabel="Make active"
          onConfirm={confirmActivate}
          isPending={update.isPending}
        />
      ) : null}
      {isWriter && actions.cancel ? (
        <ConfirmationDialog
          open={cancelling}
          onOpenChange={setCancelling}
          title={`Cancel the arrangement with ${arrangement.tenantName}?`}
          description="The arrangement becomes read-only and the tenant's normal arrears reminders resume. Give the reason; it is kept with the record."
          confirmLabel="Cancel arrangement"
          cancelLabel="Keep it"
          destructive
          requireReason
          reasonLabel="Reason for cancelling"
          onConfirm={confirmCancel}
          isPending={cancel.isPending}
          showError
        />
      ) : null}
    </section>
  )
}
