-- The instalment schedule for the terms (the same as generateInstallmentSchedule in @leaseguard/domain).
create function private.arrangement_schedule(
  p_outstanding_balance numeric,
  p_installment_amount numeric,
  p_frequency public.installment_frequency,
  p_first_installment_date date
)
returns table (sequence integer, due_date date, amount numeric)
language sql
immutable
set search_path = ''
as $$
  with terms as (
    select ceil(p_outstanding_balance / p_installment_amount)::integer as n
  )
  select
    s.seq,
    case p_frequency
      when 'weekly' then p_first_installment_date + 7 * (s.seq - 1)
      when 'fortnightly' then p_first_installment_date + 14 * (s.seq - 1)
      else (p_first_installment_date + make_interval(months => s.seq - 1))::date
    end,
    case when s.seq = t.n then p_outstanding_balance - p_installment_amount * (t.n - 1) else p_installment_amount end
  from terms t
  cross join lateral generate_series(1, t.n) as s (seq)
  where p_outstanding_balance > 0 and p_installment_amount > 0
$$;
revoke all on function private.arrangement_schedule(numeric, numeric, public.installment_frequency, date) from public, anon, authenticated;

-- The first problem with the terms, in words, or null (the same rules as arrangementTermsProblems in @leaseguard/domain).
create function private.arrangement_terms_problem(
  p_outstanding_balance numeric,
  p_installment_amount numeric,
  p_frequency public.installment_frequency,
  p_first_installment_date date,
  p_final_installment_date date,
  p_agreed_on date
)
returns text
language plpgsql
stable
set search_path = ''
as $$
declare
  v_count integer;
  v_final date;
begin
  if p_outstanding_balance is null or p_outstanding_balance <= 0 then
    return 'The outstanding balance must be more than R 0,00.';
  end if;
  if p_installment_amount is null or p_installment_amount <= 0 then
    return 'The instalment amount must be more than R 0,00.';
  end if;
  if p_installment_amount > p_outstanding_balance then
    return 'The instalment amount cannot be more than the outstanding balance.';
  end if;
  if p_frequency is null or p_first_installment_date is null then
    return 'The instalment frequency and the first instalment date are required.';
  end if;
  if p_agreed_on is null or p_agreed_on > private.sa_today() then
    return 'The agreement date cannot be in the future.';
  end if;
  if p_first_installment_date < p_agreed_on then
    return format('The first instalment cannot be before the agreement date (%s).', to_char(p_agreed_on, 'DD Mon YYYY'));
  end if;
  v_count := ceil(p_outstanding_balance / p_installment_amount)::integer;
  if v_count > 260 then
    return format('This schedule has %s instalments; at most 260 are allowed. Raise the instalment amount.', v_count);
  end if;
  select max(s.due_date) into v_final
  from private.arrangement_schedule(p_outstanding_balance, p_installment_amount, p_frequency, p_first_installment_date) s;
  if p_final_installment_date is not null and p_final_installment_date <> v_final then
    return format('The final instalment of this schedule is due on %s (%s %s), not %s.',
      to_char(v_final, 'DD Mon YYYY'), v_count, case when v_count = 1 then 'instalment' else 'instalments' end,
      to_char(p_final_installment_date, 'DD Mon YYYY'));
  end if;
  return null;
end;
$$;
revoke all on function private.arrangement_terms_problem(numeric, numeric, public.installment_frequency, date, date, date)
  from public, anon, authenticated;

-- Replaces an arrangement's instalments with the schedule of its terms.
create function private.write_arrangement_schedule(p_company_id uuid, p_arrangement_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_arrangement public.payment_arrangements;
begin
  select * into v_arrangement from public.payment_arrangements a where a.company_id = p_company_id and a.id = p_arrangement_id;
  delete from public.arrangement_installments i where i.company_id = p_company_id and i.arrangement_id = p_arrangement_id;
  insert into public.arrangement_installments (company_id, arrangement_id, sequence, due_date, amount)
  select p_company_id, p_arrangement_id, s.sequence, s.due_date, s.amount
  from private.arrangement_schedule(
    v_arrangement.outstanding_balance, v_arrangement.installment_amount, v_arrangement.frequency,
    v_arrangement.first_installment_date
  ) s;
end;
$$;
