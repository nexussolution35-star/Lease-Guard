-- Applies to every role (the service role included): these are product rules, not permissions.
create function private.guard_payment_arrangement()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_closed constant public.arrangement_status[] := '{completed,defaulted,cancelled}';
  v_other record;
begin
  if tg_op = 'UPDATE' then
    if new.tenant_id is distinct from old.tenant_id or new.property_id is distinct from old.property_id
       or new.unit_id is distinct from old.unit_id or new.lease_id is distinct from old.lease_id
       or new.agreed_by_user_id is distinct from old.agreed_by_user_id then
      raise exception 'An arrangement''s tenant, property, unit, lease and who agreed it are fixed. Cancel it and record a new one.'
        using errcode = 'P0001';
    end if;
    if old.status = any (v_closed) then
      raise exception 'This arrangement is % and can no longer change.', private.arrangement_status_label(old.status)
        using errcode = 'P0001';
    end if;
    if new.status is distinct from old.status and not (
      (old.status = 'proposed' and new.status in ('active', 'cancelled'))
      or (old.status = 'active' and new.status = any (v_closed))
    ) then
      raise exception 'An arrangement that is % cannot become %.',
        private.arrangement_status_label(old.status), private.arrangement_status_label(new.status)
        using errcode = 'P0001';
    end if;
  end if;

  if new.status = any (v_closed) and (tg_op = 'INSERT' or old.status <> all (v_closed)) then
    if (select auth.uid()) is not null then
      new.closed_on := private.sa_today();
      new.closed_by_user_id := (select auth.uid());
    else
      new.closed_on := coalesce(new.closed_on, private.sa_today());
    end if;
  end if;

  if new.status = 'active' and (tg_op = 'INSERT' or old.status <> 'active') then
    select a.agreed_on, t.trading_name into v_other
    from public.payment_arrangements a
    join public.tenants t on t.company_id = a.company_id and t.id = a.tenant_id
    where a.company_id = new.company_id and a.tenant_id = new.tenant_id and a.status = 'active' and a.id <> new.id;
    if found then
      raise exception '% already has an active payment arrangement (agreed on %). Close or cancel it first.',
        v_other.trading_name, to_char(v_other.agreed_on, 'DD Mon YYYY')
        using errcode = 'P0001';
    end if;
  end if;
  return new;
end;
$$;
revoke all on function private.guard_payment_arrangement() from public, anon, authenticated;

create trigger guard_change before insert or update on public.payment_arrangements
  for each row execute function private.guard_payment_arrangement();

